const {test,expect}=require('@playwright/test');
const {waitForParticipantReady}=require('./ui-helpers');

for(const width of [320,393])for(const language of ['tr','en'])test(`free economy real rewards ${language} ${width}px`,async({page},info)=>{
  test.skip(process.env.GRIDSHARD_E2E_FREE_ECONOMY!=='1','Owned isolated future-release fixture only');
  test.setTimeout(120000);
  await page.setViewportSize({width,height:width===320?568:852});
  await page.goto('/?e2e=1');await waitForParticipantReady(page,60000);
  const seeded=await page.evaluate(async()=>{
    const owner=GridshardAuth.session.playerId;
    const response=await fetch(`/__e2e/free-economy/${owner}/prepare`,{method:'POST',headers:{'x-gridshard-e2e':'free-economy-local-only'}});
    if(!response.ok)throw new Error('Fixture failed '+response.status);
    return response.json();
  });
  await page.reload();await waitForParticipantReady(page,60000);
  await page.evaluate(l=>GridshardI18n.apply(l),language);
  await page.locator('#lobby-menu-button').click();await page.locator('#lobby-menu [data-open-screen="daily"]').click();
  await page.locator('#rewards-hub-screen [data-open-screen="daily-missions"]').click();
  const first=page.locator('.daily-mission-card[data-mission="complete_battles"]');
  await expect(first.locator('[data-reward-kind="circuit_credits"]')).toContainText('+15');
  await expect(first.locator('[data-reward-kind="flux_shards"]')).toContainText('+15');
  const claimed=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().includes('/engagement/missions/complete_battles/claim'));
  await first.locator('[data-mission-claim]').click();
  const receipt=(await(await claimed).json()).daily_mission_receipt;
  expect(receipt.circuit_credits).toBe(15);expect(receipt.flux_shards).toBe(15);
  await expect(first.locator('[data-mission-claim]')).toBeDisabled();
  await page.locator('#mission-tab-seasonal').click();
  await expect(page.locator('.daily-mission-card[data-mission="season_battles_20"] [data-reward-kind="circuit_credits"]')).toContainText('+200');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:info.outputPath('free-economy-orders.png')});
  await page.locator('#daily-missions-screen .navigation-back').click();
  await page.locator('#rewards-hub-screen [data-open-screen="daily-rewards"]').click();
  const login=page.locator('#monthly-login-track .monthly-login-card').first();
  const loginReward=seeded.profile.engagement.daily_login.rewards[0];
  await expect(login.locator('[data-reward-kind="circuit_credits"] strong')).toHaveText(`+${loginReward.circuit_credits}`);
  await expect(login.locator('[data-reward-kind="flux_shards"] strong')).toHaveText(`+${loginReward.flux_shards}`);
  await page.screenshot({path:info.outputPath('free-economy-login.png')});
  await page.locator('#daily-rewards-screen .navigation-back').click();
  await page.locator('#rewards-hub-screen [data-open-screen="rewards"]').click();
  const roadIndex=seeded.profile.engagement.reward_track.findIndex(r=>r.circuit_credits>0&&r.flux_shards>0);
  expect(roadIndex).toBeGreaterThanOrEqual(0);
  const freeRoadChests=page.locator('#season-reward-track .season-pass-cell:not(.is-premium) .reward-chest-button');
  await expect(freeRoadChests).toHaveCount(40);
  await freeRoadChests.nth(roadIndex).click();
  const previewPanel=page.locator('.reward-preview-panel');
  await expect(previewPanel).toBeVisible();
  const roadReward=seeded.profile.engagement.reward_track[roadIndex];
  await expect(previewPanel.locator('.reward-preview-row').filter({hasText:language==='en'?'Circuit Credits':'Devre Kredisi'}).locator('strong')).toHaveText(`+${roadReward.circuit_credits}`);
  await expect(previewPanel.locator('.reward-preview-row').filter({hasText:language==='en'?'Flux':'Akı'}).locator('strong')).toHaveText(`+${roadReward.flux_shards}`);
  await page.screenshot({path:info.outputPath('free-economy-road.png')});
  expect(seeded.first_result.flux_shards_awarded).toBe(2);
  const preview=await page.evaluate(result=>window.__GRIDSHARD_TEST_API.previewEconomyResult(result),seeded.first_result);
  expect(preview.progression.economyReward).toBeTruthy();expect(preview.fluxHidden).toBe(false);
  await expect(page.locator('#post-match-flux-card')).toBeVisible();
  await expect(page.locator('#post-match-flux-reward')).toHaveText('+2');
  await expect(page.locator('#post-match-credit-reward')).toHaveText('+52');
  await expect(page.locator('#post-match-flux-limit')).toHaveText(language==='en'?'Daily matches: 1/6':'Günlük maç: 1/6');
  const boxes=await page.locator('#post-match-reward-list > article:visible').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {left:r.left,right:r.right,width:r.width};}));
  expect(boxes).toHaveLength(4);expect(boxes.every(b=>b.width>70&&b.left>=0&&b.right<=width)).toBe(true);
  await page.screenshot({path:info.outputPath('free-economy-match.png')});
  await page.evaluate(result=>window.__GRIDSHARD_TEST_API.previewEconomyResult(result),seeded.capped_result);
  await expect(page.locator('#post-match-flux-reward')).toHaveText('+0');
  await expect(page.locator('#post-match-flux-limit')).toContainText('6/6');
});
