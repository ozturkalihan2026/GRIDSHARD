  function applyPatterns(value, patterns) {
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    return null;
  }

  function splitTranslate(value, separator, translate) {
    if (!value.includes(separator)) return null;
    const parts = value.split(separator).map((part) => part.trim());
    const translated = parts.map((part) => translate(part));
    return translated.some((part, index) => part !== parts[index]) ? translated.join(separator) : null;
  }

