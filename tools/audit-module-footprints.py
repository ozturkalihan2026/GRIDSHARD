"""Measure registered opaque artwork; no image modification or runtime work."""
import json
import sys
from pathlib import Path
from functools import lru_cache
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]

@lru_cache(None)
def bounds(src):
    with Image.open(ROOT / 'client' / src) as image:
        alpha = image.convert('RGBA').getchannel('A').point(lambda x: 255 if x > 140 else 0)
        x0, y0, x1, y1 = alpha.getbbox()
        band = alpha.crop((0, y1 - max(1, round((y1-y0)*.18)), image.width, y1)).getbbox()
        return (x0/image.width,y0/image.height,x1/image.width,y1/image.height,
                band[0]/image.width,band[2]/image.width)

def audit():
    text = (ROOT / 'client/src/module-layer-data.js').read_text(encoding='utf-8')
    data = json.loads(text.split('Object.freeze(', 1)[1].split(');', 1)[0])
    out = {}
    for name, layer in data.items():
        poses = list(layer.get('heads', {}).values()) or [layer['art']]
        boxes, feet, centres = [], [], []
        for pose in poses:
            parts = ([layer['base']] if layer.get('base') else []) + [pose]
            b = [(p['left']+bounds(p['src'])[0]*p['size'],p['top']+bounds(p['src'])[1]*p['size'],
                  p['left']+bounds(p['src'])[2]*p['size'],p['top']+bounds(p['src'])[3]*p['size']) for p in parts]
            boxes.append([min(x[0] for x in b),min(x[1] for x in b),max(x[2] for x in b),max(x[3] for x in b)])
            base = layer.get('base') or pose
            bb = bounds(base['src'])
            feet.append((bb[5]-bb[4])*base['size'])
            centres.append(base['left']+(bb[4]+bb[5])*base['size']/2)
        out[name] = {'width':round(max(b[2]-b[0] for b in boxes),4),
                     'height':round(max(b[3]-b[1] for b in boxes),4),
                     'left':round(min(b[0] for b in boxes),5),
                     'top':round(min(b[1] for b in boxes),5),
                     'right':round(max(b[2] for b in boxes),5),
                     'footMin':round(min(feet),4),'footMax':round(max(feet),4),
                     'footCentre':round(sum(centres)/len(centres),5),
                     'bottom':round(max(b[3] for b in boxes),4)}
    return out

if __name__ == '__main__':
    result = audit()
    if '--write-fit' in sys.argv or '--check-fit' in sys.argv:
        file = ROOT / 'client/src/module-layer-data.js'
        text = file.read_text(encoding='utf-8')
        data = json.loads(text.split('Object.freeze(',1)[1].split(');',1)[0])
        checked = []
        for name, fit in result.items():
            if data[name].get('core'):
                continue
            # One canonical visible extent: cores=1, EVERY module=.85.
            # No battery exception and no dependence on cell row/column.
            reduction = .85
            size = reduction / max(fit['width'],fit['height'])
            left = .5-size*fit['footCentre']
            # Keep the pedestal centre unless a leaning/turning silhouette
            # would cross the neighbouring socket after the requested zoom.
            if size*(fit['right']-fit['left']) > 1:
                left = .5-size*(fit['left']+fit['right'])/2
            else:
                left = max(-size*fit['left'],min(1-size*fit['right'],left))
            frame = {'size':round(size,5),'left':round(left,5),
                     'top':round(1-size*fit['bottom'],5)}
            if '--check-fit' in sys.argv:
                assert data[name].get('socketFit') == frame, name + ': stale socket registration'
            else:
                data[name]['socketFit'] = frame
                data[name]['socketBounds'] = fit
            checked.append({'id':name,'scale':reduction,'stage':frame,
                            'width':round(fit['width']*size,4),'height':round(fit['height']*size,4),
                            'centreError':round(abs(frame['left']+frame['size']*fit['footCentre']-.5),6)})
        if '--write-fit' in sys.argv:
            file.write_text('/* Generated by tools/prepare-module-layers.cjs and tools/audit-module-footprints.py. */\n'
                +'globalThis.GridshardModuleLayerData = Object.freeze('+json.dumps(data,ensure_ascii=False,indent=1)+');\n'
                +'if (typeof module !== "undefined" && module.exports) module.exports = globalThis.GridshardModuleLayerData;\n',encoding='utf-8')
        if '--json' in sys.argv:
            print(json.dumps({'modules':checked,'allReduced':all(m['scale']<1 for m in checked)},indent=2))
        else:
            print('Verified' if '--check-fit' in sys.argv else 'Registered',
                  'measured socket fits for',len(checked),'modules')
    else:
        print(json.dumps(result,ensure_ascii=False,indent=2))
