"""Offline catalog/period preparation; never connects to the production server."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))
from app.cosmetic_releases import CATALOG_PATH, CosmeticReleaseRegistry


def frontend_catalog(registry):
    result = {"themes": [{"id":t["id"],"nameTr":t["name_tr"],"nameEn":t["name_en"]} for t in registry.document["themes"]],
              "avatarFrames": [], "backgrounds": [], "teamEmblems": {}, "teamFrames": {}, "teamNameColors": {}}
    for item in registry.items.values():
        look = item["look"]
        published = any(r["status"] in {"published","retired"} and any(item["id"] in p["cosmetics"].values() for p in r["placements"]) for r in registry.releases.values())
        view = {"id": item["id"], "theme":item["theme"], "upcoming":not published, "nameTr": item["name_tr"], "nameEn": item["name_en"], **look}
        field = item["field"]
        if field == "avatar_frame_id":
            result["avatarFrames"].append(view)
        elif field == "profile_background_id":
            result["backgrounds"].append({**view, "colors": [look["accent"], look["color"]]})
        else:
            key = {"team_emblem_id": "teamEmblems", "team_frame_id": "teamFrames", "team_name_color_id": "teamNameColors"}[field]
            if field == "team_emblem_id":
                view["path"] = '<path d="' + look["path"] + '"/>'
            result[key][item["id"]] = view
    return result


def render_frontend(registry):
    return '// Generated by tools/prepare_liveops_rewards.py sync. Ownership stays on the server.\n' + 'globalThis.GRIDSHARD_LIVEOPS_COSMETICS = Object.freeze(' + json.dumps(frontend_catalog(registry), ensure_ascii=False, separators=(",", ":")) + ');\n'


def render_styles(registry):
    lines = ["/* Generated authored motifs; static CSS/SVG, no battle or ownership effects. */"]
    borders = {"arcs": ("double", "50%"), "rays": ("ridge", "7px"), "tides": ("solid", "16px")}
    for item in registry.items.values():
        identity, look, field = item["id"], item["look"], item["field"]
        color, accent, pattern = look["color"], look["accent"], look["pattern"]
        style, radius = borders[pattern]
        if field == "avatar_frame_id":
            selector = ':root body[data-app-screen] .profile-avatar[data-frame="' + identity + '"]:not([data-frame="none"])'
            lines.append(selector + ' { --g5-rim:' + color + '; --g5-rim-dark:' + accent + '; border:4px ' + style + ' ' + color + ' !important; border-radius:' + radius + ' !important; box-shadow:inset 0 2px 2px #ffffff55,inset 0 -3px 2px ' + accent + ',0 2px 0 #041322,0 0 0 1px ' + accent + ' !important; }')
        elif field == "profile_background_id":
            decoration = {
                "arcs": 'radial-gradient(ellipse at 15% 110%,transparent 38%,' + color + '40 39% 44%,transparent 45%)',
                "rays": 'repeating-conic-gradient(from -20deg at 85% 50%,' + color + '25 0deg 8deg,transparent 8deg 24deg)',
                "tides": 'repeating-radial-gradient(ellipse at 50% 110%,transparent 0px 12px,' + color + '30 13px 16px,transparent 17px 28px)',
            }[pattern]
            background = decoration + ',linear-gradient(130deg,' + accent + ',#102841)'
            selector = ':root body[data-app-screen] :is(#app-progress-ribbon,#profile-summary-panel .profile-identity-card,#public-profile-dialog #public-profile-identity,#cosmetic-collection-player)[data-profile-background="' + identity + '"]'
            swatch = ':root body[data-app-screen] #avatar-customization-screen .profile-background-choice[data-background-id="' + identity + '"] .profile-background-swatch'
            lines.append(selector + ', ' + swatch + ' { background:' + background + ' !important; }')
        elif field == "team_frame_id":
            selector = ':root body[data-app-screen] :is(#team-screen,#team-profile-dialog,#cosmetic-collection-dialog) :is(#team-identity-card,#team-appearance-preview,.team-public-identity)[data-team-frame="' + identity + '"]'
            swatch = ':root body[data-app-screen] #team-screen .team-option-frame[data-team-frame="' + identity + '"]'
            lines.append(selector + ', ' + swatch + ' { border:3px ' + style + ' ' + color + ' !important; border-radius:' + ("12px" if radius == "50%" else radius) + ' !important; box-shadow:inset 0 2px 2px #ffffff55,inset 0 -3px 2px ' + accent + ',0 2px 0 #041322 !important; }')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["validate", "sync", "reserve", "publish", "coverage"])
    parser.add_argument("--cycles", type=int, default=2)
    parser.add_argument("--source")
    parser.add_argument("--period-id")
    parser.add_argument("--release-id")
    args = parser.parse_args()
    registry = CosmeticReleaseRegistry(json.loads(CATALOG_PATH.read_text(encoding="utf-8")))
    if args.command == "coverage":
        if not 1 <= args.cycles <= 12:
            parser.error("cycles must be between 1 and 12")
        per_cycle = {"avatar_frame_id":6,"profile_background_id":6,"team_emblem_id":1,"team_frame_id":1,"team_name_color_id":1}
        report = []
        for field, count in per_cycle.items():
            available = sum(item["field"] == field and item["status"] == "approved" and item["id"] not in registry.used for item in registry.items.values())
            required = count * args.cycles
            report.append({"field":field,"ready_unassigned":available,"required":required,"create_and_review":max(0,required-available)})
        print(json.dumps({"cycles":args.cycles,"production_changed":False,"content_tasks":report},ensure_ascii=False,indent=2))
        return
    if args.command == "reserve":
        if not all((args.source, args.period_id, args.release_id)):
            parser.error("reserve requires --source, --period-id, --release-id")
        registry = registry.reserve(args.source, args.period_id, args.release_id)
    elif args.command == "publish":
        if not args.release_id:
            parser.error("publish requires --release-id")
        registry = registry.publish(args.release_id)
    if args.command in {"reserve", "publish"}:
        CATALOG_PATH.write_text(json.dumps(registry.document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    output = ROOT / "client/src/liveops-cosmetic-catalog.js"
    expected = render_frontend(registry)
    css_output = ROOT / "client/src/liveops-cosmetics-v1.css"
    expected_css = render_styles(registry)
    i18n_output = ROOT / "client/src/i18n-catalog.js"
    i18n_source = i18n_output.read_text(encoding="utf-8")
    start_marker = "    // liveops-cosmetics:begin\n"
    end_marker = "    // liveops-cosmetics:end\n"
    translations = start_marker + ''.join('    ' + json.dumps(item["name_tr"],ensure_ascii=False) + ':' + json.dumps(item["name_en"],ensure_ascii=False) + ',\n' for item in [*registry.document["themes"],*registry.items.values()]) + end_marker
    if args.command == "sync":
        output.write_text(expected, encoding="utf-8")
        css_output.write_text(expected_css, encoding="utf-8")
        if start_marker in i18n_source:
            start = i18n_source.index(start_marker)
            end = i18n_source.index(end_marker, start) + len(end_marker)
            i18n_source = i18n_source[:start] + translations + i18n_source[end:]
        else:
            anchor = '  const translations = Object.freeze({\n'
            i18n_source = i18n_source.replace(anchor,anchor+translations,1)
        i18n_output.write_text(i18n_source,encoding="utf-8")
    elif not output.exists() or output.read_text(encoding="utf-8") != expected:
        raise SystemExit("Client catalog differs; run sync and review the generated change")
    elif not css_output.exists() or css_output.read_text(encoding="utf-8") != expected_css:
        raise SystemExit("Client cosmetic styles differ; run sync and review the generated change")
    elif translations not in i18n_source:
        raise SystemExit("Client cosmetic translations differ; run sync")
    print(json.dumps({"items": len(registry.items), "reserved_items": len(registry.used),
                      "releases": len(registry.releases), "production_changed": False}))


if __name__ == "__main__":
    main()
