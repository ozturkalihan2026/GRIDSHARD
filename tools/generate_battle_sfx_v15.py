"""Original, short, deterministic weapon/contact sounds; no external samples.

Only new WAV names are written. Existing music and compressed masters stay intact.
The already-bound cooling cue is regenerated by generate_support_vfx_audio.py.
"""
import math
import random
import struct
import wave
from pathlib import Path

RATE = 22050
OUT = Path(__file__).resolve().parents[1] / "client" / "assets" / "audio"
SOUNDS = {"laser_pulse_v2": .24, "laser_burn": .72, "rocket_launch": .34, "missile_explosion": .66,
          "kinetic_hit": .22, "electrical_hit": .28, "shield_absorb": .3}


def render(name, duration):
    rng = random.Random(15017)
    low = smooth = 0.0
    samples = []
    for i in range(round(RATE * duration)):
        t = i / RATE
        noise = rng.uniform(-1, 1)
        low += (noise - low) * .045
        smooth += (noise - smooth) * .32
        attack = min(1, t / .006)
        release = min(1, (duration - t) / .055)
        if name == "laser_pulse_v2":
            # Soft descending energy impulse, no noise/hiss. A slow attack and
            # raised-cosine release prevent clicks; no sustained ringing tail.
            phase = 2 * math.pi * (650 * t - 480 * t * t)
            value = math.sin(phase) + .16 * math.sin(2 * phase) + .12 * math.sin(2 * math.pi * 160 * t)
            envelope = min(1, t / .014) * math.sin(math.pi * t / duration) ** 1.4 * math.exp(-t * 8)
        elif name == "laser_burn":
            # Hot, granular electrical sizzle over a restrained power buzz.
            buzz = math.sin(2 * math.pi * (170 * t + 35 * t * t))
            value = .6 * (smooth - low) * (.8 + .2 * math.sin(2 * math.pi * 37 * t)) + .07 * buzz
            envelope = attack * release * (.8 + .2 * math.exp(-t * 12))
        elif name == "rocket_launch":
            value = .65 * smooth + .5 * low
            envelope = attack * release * math.sin(math.pi * min(.94, t / duration)) ** .5
        elif name == "missile_explosion":
            rumble = math.sin(2 * math.pi * (75 * t - 24 * t * t))
            value = .9 * low + .25 * smooth * math.exp(-t * 12) + .11 * rumble
            envelope = attack * release * math.exp(-t * 5)
        elif name == "kinetic_hit":
            value = .7 * low + .2 * smooth + .13 * math.sin(2 * math.pi * (130 * t - 200 * t * t))
            envelope = attack * release * math.exp(-t * 23)
        elif name == "electrical_hit":
            value = (noise - smooth) * (.45 + .35 * math.sin(2 * math.pi * 71 * t) ** 4)
            envelope = attack * release * math.exp(-t * 13)
        else:  # A noise-based energy absorption, without the old ringing partials.
            value = .65 * smooth + .5 * low
            envelope = attack * release * math.exp(-t * 9)
        samples.append(value * envelope)
    gain = (.26 if name == "laser_pulse_v2" else .46) / max(abs(v) for v in samples)
    return [round(v * gain * 32767) for v in samples]


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=list(SOUNDS), help="Generate one sound without touching other assets")
    args = parser.parse_args()
    for name, duration in SOUNDS.items():
        if args.only and name != args.only:
            continue
        output = OUT / (name + ".wav")
        with wave.open(str(output), "wb") as audio:
            audio.setnchannels(1)
            audio.setsampwidth(2)
            audio.setframerate(RATE)
            audio.writeframes(b"".join(struct.pack("<h", v) for v in render(name, duration)))
        print(f"{name}: {output.stat().st_size} bytes")
